def create_question_chunks(data_dict, chunk_size=30):
  keys = list(data_dict.keys())
  chunks = {}
  for i in range(0, len(keys), chunk_size):
    sub_keys = keys[i : i + chunk_size]
    start_q = sub_keys[0]
    end_q = sub_keys[-1]
    label = f"📌 {start_q}번 ~ {end_q}번 ({len(sub_keys)}문항)"
    chunks[label] = {k: data_dict[k] for k in sub_keys}
  return chunks


QUESTION_CHUNKS = create_question_chunks(ALL_QUESTIONS, chunk_size=30)


def send_email_notification(
    student_name,
    range_title,
    score,
    correct_count,
    total_q,
    wrong_str,
    photo_path=None,
):
  if (
      SENDER_EMAIL == "your_email@gmail.com"
      or SENDER_PASSWORD == "your_app_password"
  ):
    return

  try:
    msg = MIMEMultipart()
    msg["From"] = SENDER_EMAIL
    msg["To"] = RECEIVER_EMAIL
    msg["Subject"] = (
        f"[과제 제출 알림] {student_name} 학생 - {range_title} ({score}점)"
    )

    body = f"""
        안녕하세요 박지호 선생님,

        {student_name} 학생이 과제 답안을 제출했습니다.

        ■ 학생명: {student_name}
        ■ 과제 범위: {range_title}
        ■ 맞은 개수: {correct_count} / {total_q} 개
        ■ 환산 점수: {score} 점
        ■ 오답 문항: {wrong_str}

        감사합니다.
        """
    msg.attach(MIMEText(body, "plain"))

    if photo_path and os.path.exists(photo_path):
      with open(photo_path, "rb") as f:
        img = MIMEImage(f.read())
        img.add_header(
            "Content-Disposition",
            "attachment",
            filename=os.path.basename(photo_path),
        )
        msg.attach(img)

    server = smtplib.SMTP("smtp.gmail.com", 587)
    server.starttls()
    server.login(SENDER_EMAIL, SENDER_PASSWORD)
    server.send_message(msg)
    server.quit()
  except Exception as e:
    st.error(f"이메일 알림 전송 중 오류 발생: {e}")


